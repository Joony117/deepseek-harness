// E2E perf probe: drive one headless dsh session against the local Qwen server
// through the recording proxy, then report what the audit's checks ask for.
//
//   node scripts/qwen-e2e/run.mjs --scenario quick --harness E:/deepseek-harness --label baseline
//
// Output lands in <out>/<label>-<scenario>-<stamp>/: requests.jsonl (proxy),
// heap.jsonl (dsh heap), config.yml (dump), events summary, report.json, report.md.
import { spawn, execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync, existsSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { homedir } from 'node:os'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parseArgs } from 'node:util'
import { startProxy } from './proxy.mjs'
import { writeFixture } from './fixture.mjs'
import { findSessionDir, latestLog, readSessionLog } from './session-log.mjs'
import { analyze, renderMarkdown } from './analyze.mjs'

const here = dirname(fileURLToPath(import.meta.url))

// Declared window is what dsh believes; the server keeps its real 200K either way.
// `quick` declares 120K so the default 65,536 headroom (#8785) fires early and cheaply.
export const SCENARIOS = {
  quick: { contextWindow: 120000, files: 24, toolChangeAfter: 6 },
  full: { contextWindow: 200000, files: 40, toolChangeAfter: 10 },
  smoke: { contextWindow: 200000, files: 3, toolChangeAfter: 1 },
}

const { values: a } = parseArgs({ options: {
  scenario: { type: 'string', default: 'quick' },
  harness: { type: 'string', default: 'E:/deepseek-harness' },
  label: { type: 'string', default: 'run' },
  out: { type: 'string', default: join(here, '..', '..', '.qwen-e2e-runs') },
  upstream: { type: 'string', default: 'http://127.0.0.1:8080/v1' },
  model: { type: 'string', default: 'qwen3.8-27b' },
  effort: { type: 'string', default: 'medium' },
  port: { type: 'string', default: '8089' },
  'timeout-min': { type: 'string', default: '90' },
  'extra-patch': { type: 'string', multiple: true, default: [] },
  'skip-preflight': { type: 'boolean', default: false },
  'save-bodies': { type: 'boolean', default: false }, // full request JSON per call, for prefix diffs
  mock: { type: 'boolean', default: false }, // scripted fake server: tests the plumbing, no GPU
  inject: { type: 'string' }, // JSON merged into every chat request, e.g. '{"preserve_thinking":true}'
} })

const sc = SCENARIOS[a.scenario]
if (!sc) throw new Error(`unknown scenario ${a.scenario}; one of ${Object.keys(SCENARIOS)}`)
const harness = resolve(a.harness)
const bin = join(harness, 'apps', 'cli', 'lib', 'bin.js')
if (!existsSync(bin)) throw new Error(`${bin} missing: build the harness under test first (pnpm run build)`)

if (a.mock) { a.upstream = 'http://127.0.0.1:8099/v1'; a['skip-preflight'] = true }
if (!a['skip-preflight']) {
  const base = a.upstream.replace(/\/v1\/?$/, '')
  const models = await fetch(`${base}/v1/models`, { signal: AbortSignal.timeout(3000) }).then(r => r.json())
    .catch(error => { throw new Error(`model server not reachable at ${base}: ${error.message}`) })
  if (!models.data?.some(m => m.id === a.model)) throw new Error(`server at ${base} does not serve ${a.model}`)
}

const stamp = new Date().toISOString().replace(/[:.]/g, '-')
const runDir = resolve(a.out, `${a.label}-${a.scenario}-${stamp}`)
const ws = join(runDir, 'workspace')
mkdirSync(ws, { recursive: true })
const files = writeFixture(ws, { files: sc.files })
const mock = a.mock && spawn(process.execPath, [join(here, 'mock-upstream.mjs'), '8099'], {
  stdio: 'inherit', env: { ...process.env, MOCK_WS: ws, MOCK_FILES: String(sc.files), MOCK_CHANGE_AFTER: String(sc.toolChangeAfter) },
})
if (mock) await new Promise(r => setTimeout(r, 500))

const patch = join(runDir, 'e2e.patch.yml')
writeFileSync(patch, `# Generated by scripts/qwen-e2e/run.mjs (${a.scenario})
- id: agent-default-model
  config:
    provider: e2e-qwen
    model: ${a.model}
    reasoningEffort: ${a.effort}
- id: llm-pi-ai
  config:
    providers:
      e2e-qwen:
        displayName: E2E Qwen via recording proxy
        apiKeyEnv: LOCAL_QWEN_API_KEY
        api: openai-completions
        baseURL: http://127.0.0.1:${a.port}/v1
        reasoning: ${a.effort}
        models:
          - id: ${a.model}
            name: ${a.model}
            contextWindow: ${sc.contextWindow}
            maxTokens: 32768
            reasoningEfforts:
              low: low
              medium: medium
              xhigh: xhigh
              off: none
- insert:
    - id: mcp-dyn
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        transport: stdio
        serverName: dyn
        command: !!js process.execPath
        args: !!js '[process.env.DSH_E2E_DYN_MCP]'
        reconnect:
          enabled: false
`)
const patches = [patch, ...a['extra-patch'].map(p => resolve(p))].flatMap(p => ['--patch', p])

const env = {
  ...process.env,
  LOCAL_QWEN_API_KEY: 'local',
  DSH_TELEMETRY_MODE: 'DISABLED',
  DSH_TELEMETRY_DISABLED: '1',
  DSH_E2E_DYN_MCP: join(here, 'dyn-mcp.mjs'),
  DSH_E2E_HEAP_LOG: join(runDir, 'heap.jsonl'),
  NODE_OPTIONS: `${process.env.NODE_OPTIONS ?? ''} --import ${pathToFileURL(join(here, 'heap-sampler.mjs')).href}`.trim(),
}

// 1. Effective config, as the loader composes it (defaults the plugins apply are computed in analyze).
writeFileSync(join(runDir, 'config.yml'),
  execFileSync(process.execPath, [bin, '--profile', 'headless', ...patches, '--dump-config'], { cwd: ws, env, encoding: 'utf8' }))

// 2. The session.
const t = sc.toolChangeAfter
const task = `You are processing a code base for a performance test. Follow these steps exactly.
The directory src/ holds ${files.length} files. Process them in name order, ONE file per step:
read the whole file with your file-reading tool, then append one line to NOTES.md of the form
"<file name>: <the largest integer constant you saw in it>". Do not read more than one file at a time,
do not use shell commands, and do not skip files.
After you have appended the line for file number ${t} (counting from 1), call the tool add_tool exactly once,
then call the tool extra_tool exactly once, then continue with the next file.
When every file is done, reply with the single word DONE.`
writeFileSync(join(runDir, 'task.txt'), task)

const log = join(runDir, 'requests.jsonl')
const proxy = await startProxy({ port: Number(a.port), upstream: a.upstream, log, bodies: a['save-bodies'] ? join(runDir, 'bodies') : undefined, inject: a.inject ? JSON.parse(a.inject) : undefined })
const started = Date.now()
const deadline = started + Number(a['timeout-min']) * 60_000

/** One headless invocation; output saved as <name>.stdout.jsonl / <name>.stderr.txt. */
async function turn(name, args) {
  const child = spawn(process.execPath, [bin, '--profile', 'headless', ...patches, '--json', ...args], { cwd: ws, env })
  const stdout = []
  const stderr = []
  child.stdout.on('data', c => stdout.push(c))
  child.stderr.on('data', c => stderr.push(c))
  const timer = setTimeout(() => child.kill(), Math.max(0, deadline - Date.now()))
  const code = await new Promise(r => child.on('close', r))
  clearTimeout(timer)
  writeFileSync(join(runDir, `${name}.stdout.jsonl`), Buffer.concat(stdout))
  writeFileSync(join(runDir, `${name}.stderr.txt`), Buffer.concat(stderr))
  const session = Buffer.concat(stdout).toString('utf8').split('\n')
    .map(l => { try { return JSON.parse(l) } catch { return null } })
    .find(e => e?.type === 'session')
  return { code, sessionId: session?.sessionId ?? session?.id }
}

const main = await turn('main', [task])
const sessionId = main.sessionId
// A second process adopting the same session: its first request is the "resumed step"
// (a fresh process must rebuild the exact prompt bytes or the server cache misses).
let resumeCode = null
if (sessionId && Date.now() < deadline) {
  proxy.phase = 'resume'
  resumeCode = (await turn('resume', ['--session-id', sessionId, 'How many lines does NOTES.md have now? Answer with the number only.'])).code
}
const exitCode = main.code
proxy.close()
if (mock) mock.kill()
const wallMs = Date.now() - started

// 3. Join wire records with the session log.
let events = []
let sessionLog = null
if (sessionId) {
  sessionLog = latestLog(findSessionDir(join(homedir(), '.dsh', 'sessions'), sessionId))
  events = readSessionLog(sessionLog)
}
const report = analyze({
  meta: { label: a.label, scenario: a.scenario, harness, commit: gitHead(harness), inject: a.inject, exitCode, resumeCode, wallMs, sessionId, sessionLog, ...sc },
  configYaml: join(runDir, 'config.yml'),
  requestsFile: log,
  heapFile: env.DSH_E2E_HEAP_LOG,
  events,
  notes: join(ws, 'NOTES.md'),
})
writeFileSync(join(runDir, 'report.json'), JSON.stringify(report, null, 2))
writeFileSync(join(runDir, 'report.md'), renderMarkdown(report))
console.log(renderMarkdown(report))
console.log(`\nrun dir: ${runDir}`)

function gitHead(dir) {
  try { return execFileSync('git', ['-C', dir, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim() + (execFileSync('git', ['-C', dir, 'status', '--porcelain', '--untracked-files=no'], { encoding: 'utf8' }).trim() ? '+dirty' : '') } catch { return 'unknown' }
}
